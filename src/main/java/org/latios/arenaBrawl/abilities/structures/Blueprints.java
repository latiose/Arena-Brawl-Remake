    public static StructureBlueprint defaultWallOfVines() {
        List<StructureBlueprint.BlockOffset> offsets = new ArrayList<>();

        for (int y = 0; y <= 4; y++) {
            for (int z = -1; z <= 1; z++) {
                offsets.add(new StructureBlueprint.BlockOffset(1, y, z, Material.COBBLESTONE));
            }
        }

        for (int y = 0; y <= 4; y++) {
            for (int z = -1; z <= 1; z++) {
                offsets.add(new StructureBlueprint.BlockOffset(0, y, z, Material.VINE));
            }
        }

        return new StructureBlueprint(offsets);
    }

    public static List<StructureBlueprint> growthPhases() {
        List<StructureBlueprint> phases = new ArrayList<>();

        // Phase 0: bare trunk only
        List<StructureBlueprint.BlockOffset> phase0 = new ArrayList<>();
        for (int dy = 0; dy <= 3; dy++) {
            phase0.add(new StructureBlueprint.BlockOffset(0, dy, 0, Material.OAK_LOG));
        }
        phases.add(new StructureBlueprint(phase0));

        // Phase 1: trunk + first thin layer of leaves at the top
        List<StructureBlueprint.BlockOffset> phase1 = new ArrayList<>(phase0);
        phase1.add(new StructureBlueprint.BlockOffset(0, 4, 0, Material.OAK_LEAVES));
        phases.add(new StructureBlueprint(phase1));

        // Phase 2: wider leaf ring at top
        List<StructureBlueprint.BlockOffset> phase2 = new ArrayList<>(phase1);
        phase2.add(new StructureBlueprint.BlockOffset(1, 3, 0, Material.OAK_LEAVES));
        phase2.add(new StructureBlueprint.BlockOffset(-1, 3, 0, Material.OAK_LEAVES));
        phase2.add(new StructureBlueprint.BlockOffset(0, 3, 1, Material.OAK_LEAVES));
        phase2.add(new StructureBlueprint.BlockOffset(0, 3, -1, Material.OAK_LEAVES));
        phases.add(new StructureBlueprint(phase2));

        // Phase 3: leaves extend down one more layer
        List<StructureBlueprint.BlockOffset> phase3 = new ArrayList<>(phase2);
        phase3.add(new StructureBlueprint.BlockOffset(1, 2, 0, Material.OAK_LEAVES));
        phase3.add(new StructureBlueprint.BlockOffset(-1, 2, 0, Material.OAK_LEAVES));
        phase3.add(new StructureBlueprint.BlockOffset(0, 2, 1, Material.OAK_LEAVES));
        phase3.add(new StructureBlueprint.BlockOffset(0, 2, -1, Material.OAK_LEAVES));
        phases.add(new StructureBlueprint(phase3));

        // Phase 4: fuller canopy
        List<StructureBlueprint.BlockOffset> phase4 = new ArrayList<>(phase3);
        phase4.add(new StructureBlueprint.BlockOffset(1, 3, 1, Material.OAK_LEAVES));
        phase4.add(new StructureBlueprint.BlockOffset(-1, 3, -1, Material.OAK_LEAVES));
        phase4.add(new StructureBlueprint.BlockOffset(1, 3, -1, Material.OAK_LEAVES));
        phase4.add(new StructureBlueprint.BlockOffset(-1, 3, 1, Material.OAK_LEAVES));
        phases.add(new StructureBlueprint(phase4));

        // Phase 5: full tree, top cap of leaves
        List<StructureBlueprint.BlockOffset> phase5 = new ArrayList<>(phase4);
        phase5.add(new StructureBlueprint.BlockOffset(0, 5, 0, Material.OAK_LEAVES));
        phases.add(new StructureBlueprint(phase5));

        return phases;
    }

