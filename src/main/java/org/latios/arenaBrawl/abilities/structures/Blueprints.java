    public static StructureBlueprint defaultWallOfVines() {
        List<StructureBlueprint.BlockOffset> offsets = new ArrayList<>();

        for (int y = 0; y <= 4; y++) {
            for (int z = -1; z <= 1; z++) {
                offsets.add(new StructureBlueprint.BlockOffset(1, y, z, Material.COBBLESTONE));
            }
        }

        for (int y = 0; y <= 4; y++) {
            for (int z = -1; z <= 1; z++) {
                offsets.add(new StructureBlueprint.BlockOffset(0, y, z, Material.VINE));
            }
        }

        return new StructureBlueprint(offsets);
    }

